"""
Split the generated CBRS YOLO dataset into train/val/test folders.

By default the split follows splits/cbrs_split.csv, the fixed 3946/846/848 split
used for every model and result in the paper. Set USE_SPLIT_MANIFEST = False to
draw a new random split instead (70/15/15 per LTE bandwidth group).

Usage (from the repository root):
    python scripts/data/split_yolo_dataset.py

Default input:
    dataset_medium/images
    dataset_medium/labels
    dataset_medium/metadata

Default output:
    yolo_split/train
    yolo_split/val
    yolo_split/test
    yolo_split/data.yaml
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))  # repository root

import csv
import json
import random
import shutil
from collections import defaultdict


PROJECT_ROOT = Path(__file__).resolve().parents[2]
DATASET_DIR = PROJECT_ROOT / "dataset_medium"
OUTPUT_DIR = PROJECT_ROOT / "yolo_split"
SPLIT_MANIFEST = PROJECT_ROOT / "splits" / "cbrs_split.csv"
USE_SPLIT_MANIFEST = True
FORCE_SPLIT = False
ALLOW_OVERWRITE_EXISTING_SPLIT = False

TRAIN_RATIO = 0.70
VAL_RATIO = 0.15
TEST_RATIO = 0.15
SEED = 42


def write_dataset_yaml(
    output_dir,
    train_count,
    val_count,
    test_count,
    train_ratio=TRAIN_RATIO,
    val_ratio=VAL_RATIO,
    test_ratio=TEST_RATIO,
):
    """Write YOLO data.yaml with the current output path."""
    output_dir = Path(output_dir).expanduser().resolve()
    total_count = train_count + val_count + test_count
    # No `path` key: Ultralytics and the CEDAR-YOLO loaders then resolve the
    # entries relative to the yaml file's directory. (Ultralytics resolves
    # `path: .` against the current working directory instead.)
    # Keeps yaml portable across machines (no hard-coded absolute paths).
    yaml_content = f"""# CBRS Dataset - Split for YOLO
# Auto-generated by split_yolo_dataset.py

train: train/images
val: val/images
test: test/images

names:
  0: LTE
  1: Radar

# Split ratio: Train {train_ratio*100:.0f}% / Val {val_ratio*100:.0f}% / Test {test_ratio*100:.0f}%
# Total images: {total_count}
# Train: {train_count}, Val: {val_count}, Test: {test_count}
"""

    yaml_path = output_dir / "data.yaml"
    output_dir.mkdir(parents=True, exist_ok=True)
    with open(yaml_path, "w", encoding="utf-8") as f:
        f.write(yaml_content)
    return yaml_path


def split_exists(output_dir=OUTPUT_DIR):
    output_dir = Path(output_dir).expanduser().resolve()
    split_paths = [
        output_dir / "data.yaml",
        output_dir / "train",
        output_dir / "val",
        output_dir / "test",
    ]
    return any(path.exists() for path in split_paths)


def protect_existing_split(output_dir=OUTPUT_DIR):
    output_dir = Path(output_dir).expanduser().resolve()
    if not split_exists(output_dir):
        return

    print("=" * 60)
    print("WARNING: existing split dataset detected.")
    print("=" * 60)
    print(f"Output directory: {output_dir}")
    print("This script will not run because it could overwrite or mix files in an existing split.")
    print("To intentionally recreate the split, edit split_yolo_dataset.py and set:")
    print("  ALLOW_OVERWRITE_EXISTING_SPLIT = True")
    print("  FORCE_SPLIT = True")
    print("=" * 60)
    sys.exit(1)


def read_simple_yaml(yaml_path):
    """Read the simple top-level keys used by YOLO data.yaml."""
    values = {}
    with open(yaml_path, "r", encoding="utf-8") as f:
        for raw_line in f:
            line = raw_line.strip()
            if not line or line.startswith("#") or ":" not in line:
                continue
            if raw_line[:1].isspace():
                continue

            key, value = line.split(":", 1)
            values[key.strip()] = value.strip().strip("'\"")

    return values


def resolve_yaml_entry(root_dir, entry):
    entry_path = Path(entry).expanduser()
    if entry_path.is_absolute():
        return entry_path.resolve()
    return (root_dir / entry_path).resolve()


def same_path(left, right):
    return str(Path(left).resolve()).lower() == str(Path(right).resolve()).lower()


def validate_split_yaml(output_dir=OUTPUT_DIR):
    """Validate that data.yaml points to the configured split directory."""
    output_dir = Path(output_dir).expanduser().resolve()
    yaml_path = output_dir / "data.yaml"
    errors = []

    if not yaml_path.exists():
        print(f"Error: data.yaml not found: {yaml_path}")
        sys.exit(1)

    config = read_simple_yaml(yaml_path)
    required_keys = ("train", "val", "test")   # `path` is optional, defaults to yaml's directory
    for key in required_keys:
        if not config.get(key):
            errors.append(f"missing key in data.yaml: {key}")

    if errors:
        print_split_validation_errors(yaml_path, errors)
        sys.exit(1)

    # Resolve yaml `path`:
    #   absolute  → use as-is
    #   relative (incl. ".") → resolve relative to the yaml file's directory
    #   missing   → use the yaml file's directory directly
    if "path" in config:
        p = Path(config["path"]).expanduser()
        yaml_root = p.resolve() if p.is_absolute() else (yaml_path.parent / p).resolve()
    else:
        yaml_root = yaml_path.parent.resolve()
    if not same_path(yaml_root, output_dir):
        errors.append(f"yaml path mismatch: yaml={yaml_root}, expected={output_dir}")

    expected_entries = {
        "train": output_dir / "train" / "images",
        "val": output_dir / "val" / "images",
        "test": output_dir / "test" / "images",
    }
    for split, expected_dir in expected_entries.items():
        yaml_dir = resolve_yaml_entry(yaml_root, config[split])
        if not same_path(yaml_dir, expected_dir):
            errors.append(f"yaml {split} mismatch: yaml={yaml_dir}, expected={expected_dir}")
        if not yaml_dir.exists():
            errors.append(f"yaml {split} directory does not exist: {yaml_dir}")

    for split in ("train", "val", "test"):
        labels_dir = output_dir / split / "labels"
        images_dir = output_dir / split / "images"
        if not labels_dir.exists():
            errors.append(f"missing labels directory: {labels_dir}")
        if images_dir.exists() and labels_dir.exists():
            image_count = len(list(images_dir.glob("*.png")))
            label_count = len(list(labels_dir.glob("*.txt")))
            if image_count != label_count:
                errors.append(f"{split} image/label count mismatch: images={image_count}, labels={label_count}")

    if errors:
        print_split_validation_errors(yaml_path, errors)
        sys.exit(1)

    print(f"Split dataset yaml validated: {yaml_path}")
    return yaml_path


def print_split_validation_errors(yaml_path, errors):
    print("=" * 60)
    print("Split dataset validation failed")
    print("=" * 60)
    print(f"YAML: {yaml_path}")
    for error in errors:
        print(f"  - {error}")
    print("=" * 60)


def read_split_manifest(manifest_path):
    """Return {stem: split_name} from a split manifest CSV (split,band,stem)."""
    with open(manifest_path, newline="", encoding="utf-8") as f:
        return {row["stem"]: row["split"] for row in csv.DictReader(f)}


def split_dataset(
    dataset_dir=DATASET_DIR,
    output_dir=OUTPUT_DIR,
    force=False,
    seed=SEED,
    split_manifest=None,
    train_ratio=TRAIN_RATIO,
    val_ratio=VAL_RATIO,
    test_ratio=TEST_RATIO,
):
    dataset_dir = Path(dataset_dir).expanduser().resolve()
    output_dir = Path(output_dir).expanduser().resolve()
    yaml_path = output_dir / "data.yaml"

    if not force and yaml_path.exists():
        train_imgs = output_dir / "train" / "images"
        val_imgs = output_dir / "val" / "images"
        test_imgs = output_dir / "test" / "images"

        if train_imgs.exists() and val_imgs.exists() and test_imgs.exists():
            train_count = len(list(train_imgs.glob("*.png")))
            val_count = len(list(val_imgs.glob("*.png")))
            test_count = len(list(test_imgs.glob("*.png")))

            if train_count > 0 and val_count > 0 and test_count > 0:
                print("=" * 60)
                print("Existing split found, validating data.yaml.")
                print("=" * 60)
                print(f"  Train: {train_count}")
                print(f"  Val:   {val_count}")
                print(f"  Test:  {test_count}")
                print(f"  YAML:  {yaml_path}")
                print("=" * 60)
                return validate_split_yaml(output_dir)

    print("=" * 60)
    print("Dataset split")
    print(f"Ratio: Train {train_ratio*100:.0f}% / Val {val_ratio*100:.0f}% / Test {test_ratio*100:.0f}%")
    print("=" * 60)

    images_dir = dataset_dir / "images"
    labels_dir = dataset_dir / "labels"
    metadata_dir = dataset_dir / "metadata"

    all_images = list(images_dir.glob("*.png"))
    print(f"\nTotal images: {len(all_images)}")
    if not all_images:
        print(f"Error: no images found in {images_dir}")
        sys.exit(1)

    bandwidth_groups = defaultdict(list)
    for img_path in all_images:
        base_name = img_path.stem
        meta_path = metadata_dir / f"{base_name}.json"
        bw_key = "unknown"

        if meta_path.exists():
            try:
                with open(meta_path, "r", encoding="utf-8") as f:
                    meta = json.load(f)
                bw_key = meta.get("_lte_bandwidth_folder", "unknown")
            except (OSError, json.JSONDecodeError):
                pass

        bandwidth_groups[bw_key].append(img_path)

    print("\nLTE bandwidth distribution:")
    for bw, imgs in sorted(bandwidth_groups.items()):
        print(f"  {bw}: {len(imgs)}")

    for split in ("train", "val", "test"):
        (output_dir / split / "images").mkdir(parents=True, exist_ok=True)
        (output_dir / split / "labels").mkdir(parents=True, exist_ok=True)

    train_files = []
    val_files = []
    test_files = []

    if split_manifest is not None:
        print(f"\nUsing fixed split manifest: {split_manifest}")
        assignment = read_split_manifest(split_manifest)
        image_stems = {img_path.stem for img_path in all_images}
        missing = sorted(set(assignment) - image_stems)
        unlisted = sorted(image_stems - set(assignment))
        if missing or unlisted:
            print(f"Error: images do not match the manifest "
                  f"({len(missing)} listed but missing, {len(unlisted)} not listed)")
            for stem in (missing + unlisted)[:10]:
                print(f"  {stem}")
            sys.exit(1)
        by_split = {"train": train_files, "val": val_files, "test": test_files}
        for img_path in sorted(all_images):
            by_split[assignment[img_path.stem]].append(img_path)
    else:
        random.seed(seed)
        for imgs in bandwidth_groups.values():
            random.shuffle(imgs)
            n = len(imgs)
            n_train = int(n * train_ratio)
            n_val = int(n * val_ratio)

            train_files.extend(imgs[:n_train])
            val_files.extend(imgs[n_train:n_train + n_val])
            test_files.extend(imgs[n_train + n_val:])

    print("\nSplit result:")
    print(f"  Train: {len(train_files)} ({len(train_files)/len(all_images)*100:.1f}%)")
    print(f"  Val:   {len(val_files)} ({len(val_files)/len(all_images)*100:.1f}%)")
    print(f"  Test:  {len(test_files)} ({len(test_files)/len(all_images)*100:.1f}%)")

    def copy_files(file_list, split_name):
        for img_path in file_list:
            base_name = img_path.stem
            shutil.copy(img_path, output_dir / split_name / "images" / img_path.name)

            label_path = labels_dir / f"{base_name}.txt"
            if label_path.exists():
                shutil.copy(label_path, output_dir / split_name / "labels" / f"{base_name}.txt")

    print("\nCopying files...")
    copy_files(train_files, "train")
    copy_files(val_files, "val")
    copy_files(test_files, "test")

    yaml_path = write_dataset_yaml(
        output_dir,
        len(train_files),
        len(val_files),
        len(test_files),
        train_ratio,
        val_ratio,
        test_ratio,
    )

    print(f"\nCreated data.yaml: {yaml_path}")
    print("=" * 60)
    print("Dataset split complete.")
    print("=" * 60)
    return validate_split_yaml(output_dir)


def main():
    if not ALLOW_OVERWRITE_EXISTING_SPLIT:
        protect_existing_split(OUTPUT_DIR)

    split_dataset(
        dataset_dir=DATASET_DIR,
        output_dir=OUTPUT_DIR,
        force=FORCE_SPLIT,
        seed=SEED,
        split_manifest=SPLIT_MANIFEST if USE_SPLIT_MANIFEST else None,
    )


if __name__ == "__main__":
    main()
